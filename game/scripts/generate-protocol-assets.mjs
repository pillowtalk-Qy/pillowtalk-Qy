import { createCipheriv, createHash, pbkdf2Sync, randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const contentUrl = new URL("../protocol/protocol.content.json", import.meta.url);
const outputUrl = new URL("../src/generated-protocol.ts", import.meta.url);
const content = JSON.parse(readFileSync(contentUrl, "utf8"));
const toBase64 = (value) => Buffer.from(value).toString("base64");

function gfMultiply(left, right) {
  let product = 0;
  let a = left;
  let b = right;
  for (let index = 0; index < 8; index += 1) {
    if (b & 1) product ^= a;
    const highBit = a & 0x80;
    a = (a << 1) & 0xff;
    if (highBit) a ^= 0x1b;
    b >>= 1;
  }
  return product;
}

function gfPower(value, exponent) {
  let result = 1;
  let base = value;
  let power = exponent;
  while (power > 0) {
    if (power & 1) result = gfMultiply(result, base);
    base = gfMultiply(base, base);
    power >>= 1;
  }
  return result;
}

function recoverSecret(first, second) {
  const denominator = first.x ^ second.x;
  const inverse = gfPower(denominator, 254);
  return Buffer.from(first.y.map((value, index) => (
    gfMultiply(value, gfMultiply(second.x, inverse)) ^
    gfMultiply(second.y[index], gfMultiply(first.x, inverse))
  )));
}

function encryptWithKey(key, payload) {
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  const ciphertext = Buffer.concat([cipher.update(JSON.stringify(payload), "utf8"), cipher.final()]);
  return { iv: toBase64(iv), ciphertext: toBase64(ciphertext), tag: toBase64(cipher.getAuthTag()) };
}

function encryptWithPhrase(phrase, payload) {
  const salt = randomBytes(16);
  const iterations = 120_000;
  const key = pbkdf2Sync(phrase, salt, iterations, 32, "sha256");
  return { salt: toBase64(salt), iterations, ...encryptWithKey(key, payload) };
}

const masterKey = randomBytes(32);
const coefficients = randomBytes(32);
const shares = [1, 2, 3].map((x) => ({
  x,
  y: Buffer.from(masterKey.map((value, index) => value ^ gfMultiply(coefficients[index], x))),
}));

for (let first = 0; first < shares.length; first += 1) {
  for (let second = first + 1; second < shares.length; second += 1) {
    if (!recoverSecret(shares[first], shares[second]).equals(masterKey)) throw new Error("Shamir reconstruction failed");
  }
}

const sibling = randomBytes(32);
const leaf = createHash("sha256").update(content.builder.answer).digest();
const root = createHash("sha256").update(Buffer.concat([leaf, sibling])).digest("hex");
const routeNames = ["cypherpunk", "proof", "builder"];
const routePayloads = routeNames.map((route, index) => ({
  ...content[route].capsule,
  share: { x: shares[index].x, y: toBase64(shares[index].y) },
}));

const generated = {
  protocolVersion: content.protocolVersion,
  cypherPhrase: content.cypherpunk.phrase,
  cypherTokens: content.cypherpunk.tokenOrder,
  proofCapsuleKey: content.proof.key,
  builder: { answer: content.builder.answer, options: content.builder.options, sibling: sibling.toString("hex"), root },
  capsules: {
    cypherpunk: encryptWithPhrase(content.cypherpunk.phrase, routePayloads[0]),
    proof: encryptWithPhrase(content.proof.key, routePayloads[1]),
    builder: encryptWithPhrase(content.builder.answer, routePayloads[2]),
    final: encryptWithKey(masterKey, content.final),
  },
};

writeFileSync(outputUrl, `// Generated by npm run protocol:generate.\nexport const GENERATED_PROTOCOL = ${JSON.stringify(generated, null, 2)} as const;\n`);
console.log(`Generated ${outputUrl.pathname}`);
